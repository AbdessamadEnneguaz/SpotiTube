/**
 * Get synchronized lyrics for a track, or generate intelligent rhythmic captions
 */
export function getLyricsForTrack(trackId: string, title: string, artist: string, durationSec: number = 210): LyricLine[] {
  if (TRACK_LYRICS[trackId]) {
    return TRACK_LYRICS[trackId];
  }

  const combined = `${title} ${artist}`.toLowerCase();
  if (combined.includes('7elmet') || combined.includes('helmet') || combined.includes('ado')) {
    return TRACK_LYRICS.rap_0;
  }
  if (combined.includes('silhouette') || (combined.includes('toto') && combined.includes('silhouette'))) {
    return TRACK_LYRICS.rap_1;
  }
  if (combined.includes('mghayer') || (combined.includes('toto') && combined.includes('mghayer'))) {
    return TRACK_LYRICS.rap_2;
  }
  if (combined.includes('cazafonia') || (combined.includes('dros') && combined.includes('caza'))) {
    return TRACK_LYRICS.rap_3;
  }
  if (combined.includes('didi') || (combined.includes('khaled') && combined.includes('didi'))) {
    return TRACK_LYRICS.rai_1;
  }
  if (combined.includes('aicha') || (combined.includes('khaled') && combined.includes('aicha'))) {
    return TRACK_LYRICS.rai_2;
  }
  if (combined.includes('daoudia') || combined.includes('daoudi')) {
    return TRACK_LYRICS.chaabi_1;
  }
  if (combined.includes('dardeg') || combined.includes('senhaji')) {
    return TRACK_LYRICS.chaabi_2;
  }
  if (combined.includes('kedba') || combined.includes('aatabou')) {
    return TRACK_LYRICS.chaabi_3;
  }

  // Generate pleasant synchronized lyrics / captions for any dynamic YouTube or custom track
  const estimatedDuration = durationSec > 0 ? durationSec : 200;
  const interval = Math.max(10, Math.floor(estimatedDuration / 12));

  return [
    { time: 0, text: `♪ [Playing: "${title}" by ${artist}] ♪` },
    { time: 10, text: "Kiddwave Live Synchronized Karaoke Captions" },
    { time: interval, text: `Listening to ${title} · Official Kiddwave Soundstage` },
    { time: interval * 2, text: "♪ [Instrumental Melody & Rhythm] ♪" },
    { time: interval * 3, text: `Vocals & Flow by ${artist}` },
    { time: interval * 4, text: "Feel the authentic rhythm & bass" },
    { time: interval * 5, text: "♪ [Hook & Chorus section] ♪" },
    { time: interval * 6, text: `"${title}" — Kiddwave Synchronized Captions` },
    { time: interval * 7, text: "♪ [Beat Bridge & Solos] ♪" },
    { time: interval * 8, text: "Tap any lyric line to jump directly to that part!" },
    { time: interval * 9, text: "Enjoying the high-fidelity soundstage" },
    { time: interval * 10, text: `♪ [Outro — ${artist}] ♪` }
  ];
}
